package operator;

/**
 * Operator1
 */
public class Operator1 {

    public static void main(String[] args) {
        int a = 5;
        int b = 2;
        
        int sum = a + b;
        System.out.println("a + b = " + sum);
        int diff = a-b;
        System.out.println("a - b = "+ diff);
        int multi = a*b;
        System.out.println(multi);
        int div = a/b;
        System.out.println(div);
        int mod = a%b;
        System.out.println(mod);
    }
}